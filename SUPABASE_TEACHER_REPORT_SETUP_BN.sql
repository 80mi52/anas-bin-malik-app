  FOR INSERT TO authenticated
  WITH CHECK ((teacher_id = auth.uid() AND EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.user_id = auth.uid() AND p.role = 'teacher'
  )) OR public.is_madrasa_admin());
