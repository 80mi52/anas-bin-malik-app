-- মাদ্রাসা আনাস বিন মালেক (রাঃ): শিক্ষক হাজিরা ও রিপোর্টের অতিরিক্ত সেটআপ
-- এই SQL বিদ্যমান ছাত্র/হাজিরার রেকর্ড মুছে বা রিসেট করে না।
-- Supabase Dashboard > SQL Editor-এ পুরোটা পেস্ট করে Run করুন।

-- বিদ্যমান teacher_attendance টেবিল থাকলে সেটির মধ্যেই প্রয়োজনীয় কলাম যোগ হবে।
CREATE TABLE IF NOT EXISTS public.teacher_attendance (
  id bigint generated by default as identity primary key,
  teacher_id uuid references auth.users(id) on delete set null,
  teacher_name text,
  attendance_date date not null default current_date,
  session_name text not null default 'সকাল',
  status text not null default 'উপস্থিত',
  created_at timestamptz not null default now()
);

ALTER TABLE public.teacher_attendance
  ADD COLUMN IF NOT EXISTS teacher_id uuid REFERENCES auth.users(id) ON DELETE SET NULL;
ALTER TABLE public.teacher_attendance
  ADD COLUMN IF NOT EXISTS teacher_name text;
ALTER TABLE public.teacher_attendance
  ADD COLUMN IF NOT EXISTS session_name text DEFAULT 'সকাল';
ALTER TABLE public.teacher_attendance
  ADD COLUMN IF NOT EXISTS status text DEFAULT 'উপস্থিত';
ALTER TABLE public.teacher_attendance
  ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();

CREATE INDEX IF NOT EXISTS teacher_attendance_date_idx
  ON public.teacher_attendance(attendance_date);
CREATE INDEX IF NOT EXISTS teacher_attendance_teacher_date_idx
  ON public.teacher_attendance(teacher_id, attendance_date, session_name);

ALTER TABLE public.teacher_attendance ENABLE ROW LEVEL SECURITY;

-- এই নীতিগুলো লগইন করা অ্যাকাউন্টকে শিক্ষক হাজিরা দেখতে ও জমা দিতে দেয়।
-- অ্যাপ ব্যবহারের আগে Supabase Authentication-এ শুধু বিশ্বস্ত অ্যাকাউন্ট রাখুন।
DROP POLICY IF EXISTS "anm_authenticated_teacher_attendance_read" ON public.teacher_attendance;
CREATE POLICY "anm_authenticated_teacher_attendance_read"
  ON public.teacher_attendance FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "anm_authenticated_teacher_attendance_insert" ON public.teacher_attendance;
CREATE POLICY "anm_authenticated_teacher_attendance_insert"
  ON public.teacher_attendance FOR INSERT TO authenticated
  WITH CHECK (teacher_id = auth.uid());

